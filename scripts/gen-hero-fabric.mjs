#!/usr/bin/env node
/**
 * gen-hero-fabric.mjs — freeze the home page hero's vector fabric into a module.
 *
 * The hero plays one hardcoded sheet, and it used to fetch that sheet's traced
 * footprints (`/api/export/footprints`, 23 kB over the wire) and its validated
 * OCR labels (a Supabase round trip) on every visit — two requests for data
 * that changes when a person reviews something, which is not often and never
 * while the page is open.
 *
 * This writes `src/lib/features/explore/heroFabric.ts`. Re-run it when the
 * sheet's counts move — the hero's captions read those counts out of the
 * generated file, so they cannot drift away from what is drawn.
 *
 *   node scripts/gen-hero-fabric.mjs
 *
 * Reads PUBLIC_SUPABASE_URL / PUBLIC_SUPABASE_ANON_KEY from `.env` — the same
 * anon access the browser had, so nothing here needs the service key.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/lib/features/explore/heroFabric.ts');

/** The sheet `HeroMap` plays. Keep in step with HERO_SHEET on the home page. */
const MAP_ID = '0e02b9d9-9d40-4cca-8e41-8c8373d54d3b';
const FOOTPRINT_API = 'https://maparchive.vn/api/export/footprints';

function env(key) {
  const line = readFileSync(join(ROOT, '.env'), 'utf8')
    .split('\n')
    .find((l) => l.startsWith(`${key}=`));
  if (!line) throw new Error(`${key} missing from .env`);
  return line.slice(key.length + 1).replace(/^"|"$/g, '');
}

/** Six decimals is ~11 cm. The sheet is a city plan, not a survey marker. */
const round = (n) => Number(n.toFixed(6));
const roundDeep = (v) => (typeof v === 'number' ? round(v) : v.map(roundDeep));

/**
 * EWKB hex → [lng, lat]. Little-endian point only, which is what PostGIS emits
 * here; anything else is skipped rather than guessed at. The runtime twin is
 * `parsePointHex` in `$lib/core/geo/wkb.ts` — this exists so the browser does
 * not have to carry it for the hero.
 */
function parsePoint(hex) {
  if (typeof hex !== 'string' || !hex.startsWith('0101000020')) return null;
  const bytes = Buffer.from(hex, 'hex');
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  return [view.getFloat64(9, true), view.getFloat64(17, true)];
}

const [url, key] = [env('PUBLIC_SUPABASE_URL'), env('PUBLIC_SUPABASE_ANON_KEY')];

const fc = await (await fetch(`${FOOTPRINT_API}?map_id=${MAP_ID}&status=submitted`)).json();
// Rows that could not be warped carry pixel coordinates, not degrees — drawing
// them would scatter garbage across the Gulf of Guinea. Same filter the layer
// applied at runtime.
const footprints = (fc.features ?? [])
  .filter((f) => f.properties?.geo_converted)
  .map((f) => ({
    type: 'Feature',
    // `feature_type` is the only property the layer's style reads; the other
    // fifteen columns were 50 kB of round trip nobody looked at.
    properties: { feature_type: f.properties.feature_type ?? 'other' },
    geometry: { type: f.geometry.type, coordinates: roundDeep(f.geometry.coordinates) },
  }));

const rows = await (
  await fetch(
    `${url}/rest/v1/ocr_labels?select=text,geom&map_id=eq.${MAP_ID}` +
      `&review_status=eq.validated&geom=not.is.null&limit=150`,
    { headers: { apikey: key, Authorization: `Bearer ${key}` } }
  )
).json();

const labels = rows
  .map((r) => [r.text, parsePoint(r.geom)])
  .filter(([text, point]) => text && point)
  .map(([text, [lng, lat]]) => [text, round(lng), round(lat)]);

const file = `// GENERATED by scripts/gen-hero-fabric.mjs — do not hand-edit.
//
// The home page hero's one sheet, frozen: ${footprints.length} traced footprints and
// ${labels.length} validated labels. Fetching these cost two round trips per visit for
// data that only moves when somebody reviews something. Re-run the script when
// it does; the hero's captions quote the counts below, so they follow.

export type HeroLabel = [text: string, lng: number, lat: number];

export const HERO_FOOTPRINT_COUNT = ${footprints.length};
export const HERO_LABEL_COUNT = ${labels.length};

export const HERO_FOOTPRINTS = ${JSON.stringify({ type: 'FeatureCollection', features: footprints })};

export const HERO_LABELS: HeroLabel[] = ${JSON.stringify(labels)};
`;

writeFileSync(OUT, file);
console.log(`wrote ${OUT}`);
console.log(`  footprints: ${footprints.length}`);
console.log(`  labels:     ${labels.length}`);
console.log(`  size:       ${(file.length / 1024).toFixed(1)} kB uncompressed`);
