"""Check the declared workspace layout, and keep docs/ATLAS.md in step with it.

    python3 scripts/check_workspace_layout.py                 check; fail if ATLAS.md is stale
    python3 scripts/check_workspace_layout.py --write-atlas   render docs/ATLAS.md
    python3 scripts/check_workspace_layout.py --self-check    offline asserts on synthetic data

docs/workspace-model.json is the one source. Entries may carry `purpose` (the one-line
description) and `read` (the doc to open first; a path or a list). Without `read`, the atlas
links the folder's own README.md, CLAUDE.md, SOURCE.md or VMA_SETUP.md, if git tracks one.
The atlas looks only at tracked files, so a fresh checkout and CI render the same page
(git add a new README before you re-render).
"""

import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODEL = "docs/workspace-model.json"
ATLAS = "docs/ATLAS.md"
FOLDER_DOCS = ["README.md", "CLAUDE.md", "SOURCE.md", "VMA_SETUP.md"]
HEADER = "Generated by `python3 scripts/check_workspace_layout.py --write-atlas` — do not edit by hand."
EXPECTED_LAYERS = ["sources", "holdings", "placement", "readings", "entities", "studies", "surfaces", "operations"]


def tracked_files():
    out = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return set(out.splitlines())


def is_dir(path, files):
    return any(f.startswith(path + "/") for f in files)


def read_first(entry, files):
    """Docs to open first, as repo-relative paths."""
    read = entry.get("read")
    if read:
        return [read] if isinstance(read, str) else list(read)
    path = entry["path"]
    if path in files:
        return [path]
    if entry["availability"] != "repository":
        return []
    return [f"{path}/{name}" for name in FOLDER_DOCS if f"{path}/{name}" in files]


def link(target, label, files):
    """Markdown link to a repo path, relative to docs/. Untracked paths get plain code text."""
    if target not in files and not is_dir(target, files):
        return f"`{label}`"
    return f"[{label}]({os.path.relpath(target, 'docs')}{'' if target in files else '/'})"


def render_atlas(model, files):
    out = [
        "# Atlas — where things live",
        "",
        HEADER,
        "",
        "One page: for each layer of the [workspace model](model-layout.md), the folders that belong to it,",
        "what each is for, and what to read first. Open work is in [ROADMAP](ROADMAP.md).",
        "A folder marked *local* is not in git; a fresh checkout will not have it.",
        "",
        "## Start here",
        "",
        "| Read | For |",
        "| --- | --- |",
    ]
    for item in model["start_here"]:
        out.append(f"| {link(item['path'], item['path'], files)} | {item['purpose']} |")
    for layer in model["layers"]:
        out += ["", f"## {layer['name']}", "", f"Layer `{layer['key']}`. {layer['description']}.", "", "| Folder | What it is | Read first |", "| --- | --- | --- |"]
        for entry in layer["entries"]:
            path = entry["path"]
            tag = " *(local)*" if entry["availability"] == "local" else ""
            docs = ", ".join(link(d, d[len(path) + 1 :] if d.startswith(path + "/") else d, files) for d in read_first(entry, files) if d != path)
            if path in files and not entry.get("read"):
                docs = "this file"
            out.append(f"| {link(path, path, files)}{tag} | {entry.get('purpose', 'TODO')} | {docs or '—'} |")
    out += ["", "## Frozen", "", "Kept as a record. Do not cite as current.", ""]
    out += [f"- {link(p, p, files)}" for p in model["historical"]]
    out += ["", "## Old paths", "", "These symlinks keep old scripts and citations working. Use the new path.", "", "| Old | New |", "| --- | --- |"]
    out += [f"| `{old}` | {link(new, new, files)} |" for old, new in model["compatibility"].items()]
    return "\n".join(out) + "\n"


def covered(child, declared):
    return any(d == child or d.startswith(child + "/") or child.startswith(d + "/") for d in declared)


def undeclared_folders(model, files):
    declared = {e["path"] for layer in model["layers"] for e in layer["entries"]}
    declared |= set(model["historical"]) | set(model["compatibility"]) | set(model["unlisted"])
    found = []
    for base in model["scan"]:
        prefix = base + "/" if base else ""
        children = {f[len(prefix):].split("/")[0] for f in files if f.startswith(prefix) and "/" in f[len(prefix):]}
        found += [prefix + c for c in sorted(children) if not covered(prefix + c, declared)]
    return found


def find_errors(model, files, atlas_text=None):
    errors, declared, local = [], set(), set()
    if [layer["key"] for layer in model["layers"]] != EXPECTED_LAYERS:
        errors.append("Layer order differs from docs/plans/knowledge-system-plan.md §9")
    for layer in model["layers"]:
        for entry in layer["entries"]:
            path = entry["path"]
            if path in declared:
                errors.append(f"Duplicate primary responsibility: {path}")
            declared.add(path)
            if entry["availability"] == "local":
                local.add(path)
            elif not (ROOT / path).exists():
                errors.append(f"Missing repository entry: {path}")
            if "purpose" not in entry:
                errors.append(f"No purpose (shows as TODO in the atlas): {path}")
            for doc in read_first(entry, files) if entry.get("read") else []:
                if doc not in files:
                    errors.append(f"Read-first doc is not tracked: {doc} (for {path})")
    for item in model["start_here"]:
        if item["path"] not in files:
            errors.append(f"Start-here doc is not tracked: {item['path']}")
    for old, target in model["compatibility"].items():
        alias = ROOT / old
        if not alias.is_symlink():
            errors.append(f"Missing compatibility link: {old}")
        elif alias.resolve() != (ROOT / target).resolve():
            errors.append(f"Wrong compatibility target: {old} -> {target}")
        elif target not in local and not alias.exists():
            errors.append(f"Broken compatibility link: {old}")
    for path in model["historical"]:
        if not (ROOT / path).exists():
            errors.append(f"Missing historical store: {path}")
    for folder in undeclared_folders(model, files):
        errors.append(f'Undeclared folder: {folder} (add it to a layer, or to "unlisted", in {MODEL})')
    if atlas_text is not None and atlas_text != render_atlas(model, files):
        errors.append(f"{ATLAS} is stale: run python3 scripts/check_workspace_layout.py --write-atlas")
    return errors, declared


def self_check():
    layers = [{"key": k, "name": k.title(), "description": f"The {k} layer", "entries": []} for k in EXPECTED_LAYERS]
    layers[0]["entries"] = [
        {"path": "work/a", "purpose": "Thing A", "availability": "repository"},
        {"path": "work/b", "availability": "repository", "read": "docs/b.md"},
        {"path": "work/gone", "purpose": "Not in git", "availability": "local", "read": "docs/b.md"},
        {"path": "docs/one.md", "purpose": "A doc", "availability": "repository"},
    ]
    model = {
        "layers": layers,
        "start_here": [{"path": "CLAUDE.md", "purpose": "Rules"}],
        "scan": ["", "work"],
        "unlisted": {".hidden": "tool config"},
        "historical": ["work/old"],
        "compatibility": {"work/a/link": "work/a"},
    }
    files = {"CLAUDE.md", "docs/one.md", "docs/b.md", "work/a/README.md", "work/a/x.py", "work/b/x.py", "work/old/x", ".hidden/f", "work/a/link"}
    text = render_atlas(model, files)
    assert text == render_atlas(model, files), "render is not deterministic"
    assert "| [work/a](../work/a/) | Thing A | [README.md](../work/a/README.md) |" in text
    assert "| `work/gone` *(local)* | Not in git | [docs/b.md](b.md) |" in text  # local: no link, explicit read
    assert "| [work/b](../work/b/) | TODO | [docs/b.md](b.md) |" in text  # missing purpose shows TODO
    assert "| [docs/one.md](one.md) | A doc | this file |" in text
    assert HEADER in text
    errs, _ = find_errors(model, files, atlas_text=text)
    assert any("No purpose" in e and "work/b" in e for e in errs), errs
    assert not any("stale" in e for e in errs), errs
    assert any("stale" in e for e in find_errors(model, files, atlas_text=text + "x")[0])
    assert undeclared_folders(model, files) == [], undeclared_folders(model, files)
    files |= {"work/new/x.py", "tools/y.sh", "work/old/deep/z"}
    assert undeclared_folders(model, files) == ["tools", "work/new"], undeclared_folders(model, files)
    model["unlisted"]["tools"] = "ok"
    assert undeclared_folders(model, files) == ["work/new"]
    assert covered("work", {"work/a"}) and covered("work/a/b", {"work/a"}) and not covered("work/c", {"work/a"})
    print("check_workspace_layout self-check passed")


def main():
    if "--self-check" in sys.argv:
        return self_check()
    model = json.loads((ROOT / MODEL).read_text())
    files = tracked_files()
    if "--write-atlas" in sys.argv:
        (ROOT / ATLAS).write_text(render_atlas(model, files))
        print(f"Wrote {ATLAS}")
        return
    atlas = ROOT / ATLAS
    errors, declared = find_errors(model, files, atlas.read_text() if atlas.exists() else "")
    if errors:
        print("\n".join(errors))
        raise SystemExit(1)
    print(f"Workspace layout verified: {len(declared)} primary entries and {len(model['compatibility'])} compatibility links; {ATLAS} is current.")


if __name__ == "__main__":
    main()
