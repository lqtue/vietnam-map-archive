def get_clean_iiif_base(allmaps_id):
    """Fetches the IIIF base URI and safely removes /info.json if present."""
    print(f"Resolving Allmaps ID: {allmaps_id}...")
    try:
        r = requests.get(f'https://annotations.allmaps.org/images/{allmaps_id}', timeout=15)
        if not r.ok:
            return None
        base = r.json().get('items', [{}])[0].get('target', {}).get('source', {}).get('id')
        if base:
            return base.replace('/info.json', '') # <-- Fix: Strip info.json to prevent 400 Bad Request
    except Exception as e:
        print(f"Error fetching IIIF base: {e}")
    return None

def get_iiif_tile(base_url, x, y, w, h, target_size=1024, max_retries=3):
    """Fetches a specific geographic crop from the IIIF server with retries."""
    base = base_url.rstrip('/')
    region = f"{x},{y},{w},{h}"
    size = f"{target_size},"

    tile_url = f"{base}/{region}/{size}/0/default.jpg"
    print(f"Fetching IIIF tile: {tile_url}")

    for attempt in range(max_retries):
        try:
            # Increased timeout to 120s for slow servers like Internet Archive
            r = requests.get(tile_url, timeout=120)
            r.raise_for_status()
            return Image.open(BytesIO(r.content)).convert('RGB')
        except requests.exceptions.Timeout:
            print(f"  [Attempt {attempt + 1}/{max_retries}] Timeout reached. Retrying in 5s...")
            time.sleep(5)
        except requests.exceptions.RequestException as e:
            print(f"  [Attempt {attempt + 1}/{max_retries}] Network error: {e}. Retrying in 5s...")
            time.sleep(5)
        except Exception as e:
            print(f"Failed to fetch tile: {e}")
            break # Break immediately on non-network/timeout errors (like image parsing failure)

    print("Failed to fetch tile after all retries.")
    return None


