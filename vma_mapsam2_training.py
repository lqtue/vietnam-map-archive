rows = resp.json()

annotation_cache = {}

def get_iiif_base(allmaps_id):
    if allmaps_id in annotation_cache: return annotation_cache[allmaps_id]
    try:
        r = requests.get(f'https://annotations.allmaps.org/images/{allmaps_id}', timeout=15)
        if not r.ok: return None
        base = r.json().get('items', [{}])[0].get('target', {}).get('source', {}).get('id')
        annotation_cache[allmaps_id] = base
        return base
    except: return None

# Standardized IIIF parameters: {region}/{size}/{rotation}/{quality}.{format}
ROTATION = '0'
QUALITY = 'default'
FORMAT = 'jpg'

coco_images = []
coco_annotations = []
ann_id = 1

for row in rows:
    if row.get('feature_type') != CATEGORY_FILTER:
        continue

    task = row.get('label_tasks') or {}
    maps_join = task.get('maps') or {}
    allmaps_id = row.get('allmaps_id') or task.get('allmaps_id') or maps_join.get('allmaps_id')
    if not allmaps_id: continue

    iiif_base = get_iiif_base(allmaps_id)
    if not iiif_base: continue

    pixel_ring = row.get('pixel_polygon')
    if not pixel_ring: continue

    xs, ys = [pt[0] for pt in pixel_ring], [pt[1] for pt in pixel_ring]
    x_min, y_min, x_max, y_max = min(xs), min(ys), max(xs), max(ys)
    crop_x, crop_y = max(0, round(x_min - PAD)), max(0, round(y_min - PAD))
    crop_w, crop_h = round(x_max - x_min + 2 * PAD), round(y_max - y_min + 2 * PAD)

