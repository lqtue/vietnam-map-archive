    if tile_img:
        print("\n--- Preparing MapSAM2 Inference Pipeline ---")

        # 1. Create a temporary "dummy dataset" structure for MapSAM2
        img_dir = os.path.join(TEMP_INFERENCE_DIR, 'test')
        ann_dir = os.path.join(TEMP_INFERENCE_DIR, 'annotation', 'test')
        os.makedirs(img_dir, exist_ok=True)
        os.makedirs(ann_dir, exist_ok=True)

        tile_filename = f"tile_{tx}_{ty}.png"
        img_path = os.path.join(img_dir, tile_filename)
        mask_path = os.path.join(ann_dir, tile_filename)

        # Save the real image
        tile_img.save(img_path)

        # Save a dummy ground truth mask (all black/0s) to satisfy the script
        dummy_mask = Image.new('L', tile_img.size, 0)
        dummy_mask.save(mask_path)

        # 2. Run MapSAM2 in Test Mode using the CLI
        os.chdir(MAPSAM2_DIR)
        CMD_TEST = (
            f"python train_2d.py -net sam2 -encoder {ENCODER} "
            f"-sam_ckpt {CKPT_PATH} -sam_config {SAM_CONFIG} "
            f"-data_path {TEMP_INFERENCE_DIR} -test_path {TEMP_INFERENCE_DIR} "
            f"-image_size 1024 -out_size 1024 -b 1 -rank {LORA_RANK} "
            f"-ft_ckpt {best_model_path} "
            f"-test -exp_name single_tile_inference"
        )
        print("Running prediction model (this may take a moment)...")

        # Capture output to catch any hidden errors instead of piping to tee
        result = subprocess.run(CMD_TEST, shell=True, capture_output=True, text=True)

        if result.returncode != 0:
            print(f"\n--- MapSAM2 Execution Failed (Return Code: {result.returncode}) ---")
            print(f"STDOUT:\n{result.stdout}")
            print(f"STDERR:\n{result.stderr}")
        else:
            # Save log for debugging just in case
            with open('/content/inference.log', 'w') as f:
                f.write(result.stdout)
                f.write(result.stderr)

            # 3. Locate the prediction output
            inference_log_dirs = sorted(glob.glob(f'{MAPSAM2_DIR}/logs/single_tile_inference*'), key=os.path.getmtime)

            if not inference_log_dirs:
                print("Error: MapSAM2 completed but no log directory was created.")
            else:
                inference_log_dir = inference_log_dirs[-1]
                pred_dir = os.path.join(inference_log_dir, 'Pred')

                # Use glob to find the file in case MapSAM2 appends a suffix
                stem = tile_filename.replace('.png', '')
                pred_candidates = glob.glob(os.path.join(pred_dir, f"*{stem}*.*"))

                # 4. Visualize the results
                if pred_candidates:
                    pred_path = pred_candidates[0]
                    pred_img = Image.open(pred_path).convert('L').resize(tile_img.size, Image.NEAREST)
                    pred_mask = np.array(pred_img) > 127

                    fig, axes = plt.subplots(1, 2, figsize=(14, 7))

                    # Show Original Tile
                    axes[0].imshow(tile_img)
                    axes[0].set_title(f'Original Tile ({tw}x{th} crop)')
                    axes[0].axis('off')

                    # Show Prediction Overlay
                    axes[1].imshow(tile_img)
                    overlay = np.zeros((*pred_mask.shape, 4), dtype=np.uint8)
                    overlay[pred_mask] = [255, 100, 0, 160] # Orange semi-transparent mask
                    axes[1].imshow(overlay)
                    axes[1].set_title(f'MapSAM2 Prediction: {TARGET_CATEGORY}')
                    axes[1].axis('off')

                    plt.tight_layout()
                    plt.show()

                    print(f"✓ Inference complete. Generated {(pred_mask).sum()} positive pixels.")

                    # Cleanup temp files
                    shutil.rmtree(TEMP_INFERENCE_DIR)

                else:
                    print(f"Error: Prediction file for {stem} was not generated by MapSAM2.")
                    print("Check /content/inference.log for clues.")

